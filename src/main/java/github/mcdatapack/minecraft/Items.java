    interface VersionId {
        String id(int version);

        default VersionId suffix(String suffix) {
            return v -> id(v) + suffix;
        }

        default VersionId prefix(String prefix) {
            return v -> prefix + id(v);
        }

        default VersionId suffix(VersionId suffix) {
            return v -> id(v) + suffix.id(v);
        }

        default VersionId prefix(VersionId prefix) {
            return v -> prefix.id(v) + id(v);
        }

        default VersionId toLowerCase() {
            return v -> id(v).toLowerCase();
        }
    }
    
